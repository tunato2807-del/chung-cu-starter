CREATE TABLE IF NOT EXISTS can_ho (
  ma_can_ho BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (ma_can_ho BETWEEN 0 AND 4294967295),
  so_can_ho VARCHAR(20) COLLATE app_ci NOT NULL UNIQUE,
  khoi VARCHAR(10) COLLATE app_ci NOT NULL,
  tang INTEGER NOT NULL CHECK (tang BETWEEN 0 AND 65535),
  dien_tich_m2 DECIMAL(8,2) NOT NULL,
  tinh_phi_dich_vu SMALLINT NOT NULL DEFAULT 1 CHECK (tinh_phi_dich_vu IN (0,1)),
  phien_ban BIGINT NOT NULL DEFAULT 0 CHECK (phien_ban BETWEEN 0 AND 4294967295),
  ngay_tao TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT can_ho_chk_1 CHECK (dien_tich_m2 > 0)
);

CREATE INDEX can_ho_idx_floor ON can_ho (khoi, tang);

CREATE TABLE IF NOT EXISTS cu_dan (
  ma_cu_dan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (ma_cu_dan BETWEEN 0 AND 4294967295),
  ho_va_ten VARCHAR(100) COLLATE app_ci NOT NULL,
  so_dien_thoai VARCHAR(15) COLLATE app_ci NOT NULL,
  ma_nguoi_dung BIGINT NULL UNIQUE CHECK (ma_nguoi_dung BETWEEN 0 AND 4294967295),
  phien_ban BIGINT NOT NULL DEFAULT 0 CHECK (phien_ban BETWEEN 0 AND 4294967295),
  ngay_tao TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT cu_dan_ibfk_1 FOREIGN KEY (ma_nguoi_dung) REFERENCES nguoi_dung(ma_nguoi_dung) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE IF NOT EXISTS lich_su_cu_tru (
  ma_lich_su_cu_tru BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (ma_lich_su_cu_tru BETWEEN 0 AND 4294967295),
  ma_cu_dan BIGINT NOT NULL CHECK (ma_cu_dan BETWEEN 0 AND 4294967295),
  ma_can_ho BIGINT NOT NULL CHECK (ma_can_ho BETWEEN 0 AND 4294967295),
  quan_he VARCHAR(50) NOT NULL CHECK (quan_he IN ('CHU_HO','THANH_VIEN','NGUOI_THUE')),
  tu_ngay DATE NOT NULL,
  den_ngay DATE NULL,
  ma_nguoi_ghi_nhan BIGINT NOT NULL CHECK (ma_nguoi_ghi_nhan BETWEEN 0 AND 4294967295),
  ngay_tao TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  cu_dan_dang_o BIGINT GENERATED ALWAYS AS
    (CASE WHEN den_ngay IS NULL THEN ma_cu_dan ELSE NULL END) STORED CHECK (cu_dan_dang_o BETWEEN 0 AND 4294967295),
  UNIQUE (cu_dan_dang_o),
  CONSTRAINT lich_su_cu_tru_chk_1 CHECK (den_ngay IS NULL OR den_ngay > tu_ngay),
  CONSTRAINT lich_su_cu_tru_ibfk_1 FOREIGN KEY (ma_cu_dan) REFERENCES cu_dan(ma_cu_dan) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT lich_su_cu_tru_ibfk_2 FOREIGN KEY (ma_can_ho) REFERENCES can_ho(ma_can_ho) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT lich_su_cu_tru_ibfk_3 FOREIGN KEY (ma_nguoi_ghi_nhan) REFERENCES nguoi_dung(ma_nguoi_dung) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX lich_su_cu_tru_idx_resident_period ON lich_su_cu_tru (ma_cu_dan, tu_ngay, den_ngay);

CREATE INDEX lich_su_cu_tru_idx_apartment_period ON lich_su_cu_tru (ma_can_ho, tu_ngay, den_ngay);
