CREATE TABLE IF NOT EXISTS phuong_tien (
  ma_phuong_tien BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (ma_phuong_tien BETWEEN 0 AND 4294967295),
  ma_dang_ky VARCHAR(20) COLLATE app_ci NOT NULL UNIQUE,
  ma_cu_dan BIGINT NOT NULL CHECK (ma_cu_dan BETWEEN 0 AND 4294967295),
  ma_can_ho BIGINT NOT NULL CHECK (ma_can_ho BETWEEN 0 AND 4294967295),
  ma_lich_su_cu_tru BIGINT NOT NULL CHECK (ma_lich_su_cu_tru BETWEEN 0 AND 4294967295),
  ma_dang_ky_truoc BIGINT NULL UNIQUE CHECK (ma_dang_ky_truoc BETWEEN 0 AND 4294967295),
  loai_xe VARCHAR(50) NOT NULL CHECK (loai_xe IN ('O_TO','XE_MAY','XE_DAP')),
  bien_so VARCHAR(15) COLLATE "C" NULL,
  hang_xe VARCHAR(50) COLLATE app_ci NOT NULL DEFAULT '',
  mau_sac VARCHAR(50) COLLATE app_ci NOT NULL DEFAULT '',
  ngay_dang_ky DATE NOT NULL,
  ngay_ket_thuc DATE NULL,
  ly_do_ket_thuc VARCHAR(255) COLLATE app_ci NOT NULL DEFAULT '',
  ma_nguoi_tao BIGINT NOT NULL CHECK (ma_nguoi_tao BETWEEN 0 AND 4294967295),
  ma_nguoi_ket_thuc BIGINT NULL CHECK (ma_nguoi_ket_thuc BETWEEN 0 AND 4294967295),
  phien_ban BIGINT NOT NULL DEFAULT 0 CHECK (phien_ban BETWEEN 0 AND 4294967295),
  ngay_tao TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  bien_so_dang_hoat_dong VARCHAR(15) COLLATE "C"
    GENERATED ALWAYS AS (CASE WHEN ngay_ket_thuc IS NULL THEN bien_so ELSE NULL END) STORED,
  UNIQUE (bien_so_dang_hoat_dong),
  CONSTRAINT chk_xe_ngay CHECK (ngay_ket_thuc IS NULL OR ngay_ket_thuc >= ngay_dang_ky),
  CONSTRAINT chk_xe_bien_so CHECK (loai_xe='XE_DAP' OR bien_so IS NOT NULL),
  CONSTRAINT chk_xe_ket_thuc CHECK (
    (ngay_ket_thuc IS NULL AND ma_nguoi_ket_thuc IS NULL AND ly_do_ket_thuc='') OR
    (ngay_ket_thuc IS NOT NULL AND ma_nguoi_ket_thuc IS NOT NULL AND CHAR_LENGTH(TRIM(ly_do_ket_thuc))>0)
  ),
  CONSTRAINT phuong_tien_ibfk_1 FOREIGN KEY (ma_cu_dan) REFERENCES cu_dan(ma_cu_dan) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT phuong_tien_ibfk_2 FOREIGN KEY (ma_can_ho) REFERENCES can_ho(ma_can_ho) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT phuong_tien_ibfk_3 FOREIGN KEY (ma_lich_su_cu_tru) REFERENCES lich_su_cu_tru(ma_lich_su_cu_tru) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT phuong_tien_ibfk_4 FOREIGN KEY (ma_dang_ky_truoc) REFERENCES phuong_tien(ma_phuong_tien) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT phuong_tien_ibfk_5 FOREIGN KEY (ma_nguoi_tao) REFERENCES nguoi_dung(ma_nguoi_dung) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT phuong_tien_ibfk_6 FOREIGN KEY (ma_nguoi_ket_thuc) REFERENCES nguoi_dung(ma_nguoi_dung) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX phuong_tien_idx_xe_resident ON phuong_tien (ma_cu_dan, ngay_ket_thuc);

CREATE INDEX phuong_tien_idx_xe_stay ON phuong_tien (ma_lich_su_cu_tru, ngay_ket_thuc);

CREATE INDEX phuong_tien_idx_xe_apartment_period ON phuong_tien (ma_can_ho, ngay_dang_ky, ngay_ket_thuc);

CREATE INDEX phuong_tien_idx_xe_plate_period ON phuong_tien (bien_so, ngay_dang_ky, ngay_ket_thuc);
