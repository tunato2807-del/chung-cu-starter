CREATE TABLE tien_ich (
  ma_tien_ich BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (ma_tien_ich BETWEEN 0 AND 4294967295),
  ten_tien_ich VARCHAR(120) COLLATE app_ci NOT NULL,
  vi_tri VARCHAR(160) COLLATE app_ci NOT NULL,
  mo_ta TEXT COLLATE app_ci NOT NULL,
  suc_chua INTEGER NOT NULL CHECK (suc_chua BETWEEN 0 AND 65535),
  gio_mo TIME NOT NULL,
  gio_dong TIME NOT NULL,
  toi_da_phut INTEGER NOT NULL CHECK (toi_da_phut BETWEEN 0 AND 65535),
  dat_truoc_ngay INTEGER NOT NULL CHECK (dat_truoc_ngay BETWEEN 0 AND 65535),
  dang_mo SMALLINT NOT NULL DEFAULT 1 CHECK (dang_mo IN (0,1)),
  phien_ban BIGINT NOT NULL DEFAULT 0 CHECK (phien_ban BETWEEN 0 AND 4294967295),
  ma_nguoi_tao BIGINT NOT NULL CHECK (ma_nguoi_tao BETWEEN 0 AND 4294967295),
  ngay_tao TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT tien_ich_ibfk_1 FOREIGN KEY (ma_nguoi_tao) REFERENCES nguoi_dung(ma_nguoi_dung) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT tien_ich_chk_1 CHECK (suc_chua BETWEEN 1 AND 1000),
  CONSTRAINT tien_ich_chk_2 CHECK (gio_mo >= '00:00:00' AND gio_mo < gio_dong AND gio_dong <= '23:30:00'),
  CONSTRAINT tien_ich_chk_3 CHECK (EXTRACT(SECOND FROM gio_mo)=0 AND EXTRACT(MINUTE FROM gio_mo) IN (0,30) AND EXTRACT(SECOND FROM gio_dong)=0 AND EXTRACT(MINUTE FROM gio_dong) IN (0,30)),
  CONSTRAINT tien_ich_chk_4 CHECK (toi_da_phut BETWEEN 30 AND 360 AND MOD(toi_da_phut,30)=0),
  CONSTRAINT tien_ich_chk_5 CHECK (dat_truoc_ngay BETWEEN 1 AND 90)
);

CREATE INDEX tien_ich_idx_amenities_open ON tien_ich (dang_mo,ma_tien_ich);

CREATE TABLE dat_lich_tien_ich (
  ma_dat_lich BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (ma_dat_lich BETWEEN 0 AND 4294967295),
  ma_tien_ich BIGINT NOT NULL CHECK (ma_tien_ich BETWEEN 0 AND 4294967295),
  ma_can_ho BIGINT NOT NULL CHECK (ma_can_ho BETWEEN 0 AND 4294967295),
  ma_nguoi_dat BIGINT NOT NULL CHECK (ma_nguoi_dat BETWEEN 0 AND 4294967295),
  ma_cu_dan BIGINT NOT NULL CHECK (ma_cu_dan BETWEEN 0 AND 4294967295),
  ma_lich_su_cu_tru BIGINT NOT NULL CHECK (ma_lich_su_cu_tru BETWEEN 0 AND 4294967295),
  ten_tien_ich VARCHAR(120) COLLATE app_ci NOT NULL,
  vi_tri VARCHAR(160) COLLATE app_ci NOT NULL,
  ten_nguoi_dat VARCHAR(100) COLLATE app_ci NOT NULL,
  bat_dau TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  ket_thuc TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
  so_nguoi INTEGER NOT NULL CHECK (so_nguoi BETWEEN 0 AND 65535),
  ghi_chu VARCHAR(1000) COLLATE app_ci NOT NULL,
  trang_thai VARCHAR(50) NOT NULL DEFAULT 'CHO_DUYET' CHECK (trang_thai IN ('CHO_DUYET','DA_DUYET','TU_CHOI','DA_HUY')),
  phien_ban BIGINT NOT NULL DEFAULT 0 CHECK (phien_ban BETWEEN 0 AND 4294967295),
  khoa_yeu_cau VARCHAR(36) COLLATE app_ci NOT NULL UNIQUE,
  van_tay VARCHAR(64) COLLATE app_ci NOT NULL,
  ngay_tao TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT dat_lich_tien_ich_ibfk_1 FOREIGN KEY (ma_tien_ich) REFERENCES tien_ich(ma_tien_ich) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT dat_lich_tien_ich_ibfk_2 FOREIGN KEY (ma_can_ho) REFERENCES can_ho(ma_can_ho) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT dat_lich_tien_ich_ibfk_3 FOREIGN KEY (ma_nguoi_dat) REFERENCES nguoi_dung(ma_nguoi_dung) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT dat_lich_tien_ich_ibfk_4 FOREIGN KEY (ma_cu_dan) REFERENCES cu_dan(ma_cu_dan) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT dat_lich_tien_ich_ibfk_5 FOREIGN KEY (ma_lich_su_cu_tru) REFERENCES lich_su_cu_tru(ma_lich_su_cu_tru) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT dat_lich_tien_ich_chk_1 CHECK (so_nguoi BETWEEN 1 AND 1000),
  CONSTRAINT dat_lich_tien_ich_chk_2 CHECK (ket_thuc>bat_dau AND DATE(bat_dau)=DATE(ket_thuc)),
  CONSTRAINT dat_lich_tien_ich_chk_3 CHECK (EXTRACT(SECOND FROM bat_dau)=0 AND EXTRACT(MINUTE FROM bat_dau) IN (0,30) AND EXTRACT(SECOND FROM ket_thuc)=0 AND EXTRACT(MINUTE FROM ket_thuc) IN (0,30)),
  CONSTRAINT dat_lich_tien_ich_chk_4 CHECK ((EXTRACT(EPOCH FROM (ket_thuc-bat_dau))/60) BETWEEN 30 AND 360)
);

CREATE INDEX dat_lich_tien_ich_idx_booking_overlap ON dat_lich_tien_ich (ma_tien_ich,trang_thai,bat_dau,ket_thuc);

CREATE INDEX dat_lich_tien_ich_idx_booking_apartment ON dat_lich_tien_ich (ma_can_ho,bat_dau,ma_dat_lich);

CREATE INDEX dat_lich_tien_ich_idx_booking_creator ON dat_lich_tien_ich (ma_nguoi_dat,bat_dau,ma_dat_lich);

CREATE TABLE lich_su_dat_lich (
  ma_lich_su BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (ma_lich_su BETWEEN 0 AND 4294967295),
  ma_dat_lich BIGINT NOT NULL CHECK (ma_dat_lich BETWEEN 0 AND 4294967295),
  ma_nguoi_thuc_hien BIGINT NOT NULL CHECK (ma_nguoi_thuc_hien BETWEEN 0 AND 4294967295),
  su_kien VARCHAR(50) NOT NULL CHECK (su_kien IN ('DAT_LICH','DUYET','TU_CHOI','HUY')),
  ghi_chu VARCHAR(1000) COLLATE app_ci NOT NULL,
  ngay_tao TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT lich_su_dat_lich_ibfk_1 FOREIGN KEY (ma_dat_lich) REFERENCES dat_lich_tien_ich(ma_dat_lich) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT lich_su_dat_lich_ibfk_2 FOREIGN KEY (ma_nguoi_thuc_hien) REFERENCES nguoi_dung(ma_nguoi_dung) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE INDEX lich_su_dat_lich_idx_booking_history ON lich_su_dat_lich (ma_dat_lich,ma_lich_su);
