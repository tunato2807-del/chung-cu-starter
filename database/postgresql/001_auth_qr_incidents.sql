  ma_ky_thuat_vien BIGINT NULL CHECK (ma_ky_thuat_vien BETWEEN 0 AND 4294967295),
  ma_phan_anh_goc BIGINT NULL CHECK (ma_phan_anh_goc BETWEEN 0 AND 4294967295),
  phien_ban BIGINT NOT NULL DEFAULT 0 CHECK (phien_ban BETWEEN 0 AND 4294967295),
