  CONSTRAINT phan_anh_ibfk_2 FOREIGN KEY (ma_nguoi_gui) REFERENCES nguoi_dung(ma_nguoi_dung) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT phan_anh_ibfk_3 FOREIGN KEY (ma_ky_thuat_vien) REFERENCES nguoi_dung(ma_nguoi_dung) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT phan_anh_ibfk_4 FOREIGN KEY (ma_phan_anh_goc) REFERENCES phan_anh(ma_phan_anh) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT phan_anh_chk_1 CHECK (trang_thai <> 'TRUNG' OR ma_phan_anh_goc IS NOT NULL)
